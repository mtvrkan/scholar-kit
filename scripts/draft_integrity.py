#!/usr/bin/env python3
"""draft_integrity.py — the draft files as FILES, not as prose.

Every other draft-side checker in this kit reads the manuscript as text: does a
number agree with its source, does a claim sit on the rung its evidence
supports, is a table mentioned but not embedded. This one reads the file's own
machinery — the markers, the encoding, the bytes — and asks whether the
apparatus a draft uses to describe itself is actually intact.

Three checks, all WARN-only (a human adjudicates; `--strict` opts into
blocking).

1. UNWRITTEN GENERATED BLOCKS. A block fenced by `<!-- TAG:BASLANGIC ... -->`
   / `<!-- TAG:BITIS -->` whose opening marker declares itself generated
   ("uretilmis", "üretilmiş", "generated", "do not edit", "elle duzenlemeyin")
   but whose TAG appears in no source file anywhere else in the project. The
   block SAYS a script owns it; nothing does; so it is hand-maintained under a
   sign that tells the next reader — and the next session — not to check it.

   This is the defect this script exists for, and the reason it is worth a
   check rather than a habit: its content can be correct *today* and silently
   wrong the moment the data behind it changes, which is exactly when nobody
   looks. It is also not hypothetical — in this kit's own development it
   surfaced three separate times, twice after the first fix, because the fix
   each time was to wire up the ONE block that had been noticed.

   The mirror case is reported too, and it is the cheaper half of the same
   mistake: a block whose tag IS written by a source file, but whose marker
   never says so. Nothing warns the next hand to keep out, so an edit made
   there is not wrong — it is *erased*, silently, on the next generator run,
   and the person who made it has no reason to suspect the block. One is a
   sign with nothing behind it; the other is a machine with no sign.

2. UNCLOSED OR CROSSED MARKERS. A `BASLANGIC` with no `BITIS`, a `BITIS` with
   no `BASLANGIC`, a `BITIS` that precedes its own `BASLANGIC`, or the same tag
   opened twice. Any of these makes the block's writer either fail loudly or —
   worse, depending on how it is written — replace the wrong span.

3. CONTROL CHARACTERS AND REPLACEMENT CHARACTERS. A literal control byte
   (anything below U+0020 except tab and newline) or a U+FFFD replacement
   character inside a draft. These do not come from typing; they come from a
   tool. A backslash escape that went through one interpreter too many turns
   `\\begingroup\\footnotesize` into a backspace, "egingroup", a formfeed and
   "ootnotesize" — which renders as plausible-looking prose in a terminal, is
   invisible in most editors, and reaches the typesetter as a broken command.
   A U+FFFD means bytes were decoded with the wrong codec somewhere upstream
   and the original character is already gone.

WHAT THIS DOES NOT CHECK, and cannot. Whether the content INSIDE a generated
block is the content its generator would produce — that requires running the
generator, which this script must not do. And whether prose inside a generated
block belongs there: some generators legitimately emit prose, so a caption
sitting inside a block is indistinguishable from a caption the generator wrote.
The rule that follows from that ("everything inside a marker must be
generated") is a discipline for whoever places the markers, not something a
static check can enforce.

Usage:
  python scripts/draft_integrity.py [--drafts drafts/] [--root .] [--json]
  python scripts/draft_integrity.py --strict
Exit codes: 0 ok (or warnings, default) · 1 error · 2 warnings found AND --strict.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from lib_common import die, emit, require_within_cwd

# Bir isaretin kendi metni serbesttir ("<!-- TABLO5:BASLANGIC — uretilmis, elle
# duzenlemeyin; kaynak analysis/tables_build.py -->"), o yuzden tag ADI ile
# isaretin GERI KALANI ayri yakalanir: ikincisi "uretilmis mi" sorusunu
# cevaplar, birincisi kimin yazdigini.
MARKER_RE = re.compile(
    r"<!--\s*(?P<tag>[A-Za-z0-9_-]+):(?P<kind>BASLANGIC|BITIS|BEGIN|END)"
    r"(?P<rest>[^>]*?)-->",
    re.DOTALL)

# "Uretilmis" iddiasinin isaretleri. TR ve EN, cunku bir kitin iki dilde
# calismasi bu blogun da iki dilde isaretlenmesi demektir.
GENERATED_MARKS = (
    "uretilmis", "üretilmiş", "uretilmiş", "üretilmis",
    "generated", "auto-generated", "autogenerated",
    "elle duzenlemeyin", "elle düzenlemeyin",
    "do not edit", "don't edit", "hand-edit",
)

# Bir tag'in "yazildigini" kabul ettigimiz dosya turleri. Metin dosyalari
# (drafts, build ciktilari) sayilmaz: orada gecmesi, blogun KOPYALANDIGI
# anlamina gelir, uretildigi degil.
SOURCE_SUFFIXES = {".py", ".sh", ".bash", ".js", ".ts", ".mjs", ".rb", ".pl",
                   ".lua", ".R", ".r", ".jl", ".go", ".rs", ".java", ".kt",
                   ".ps1", ".bat", ".make", ".mk", ".toml", ".cfg", ".ini"}
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv",
             "build", "exports", "dist", ".next", ".mypy_cache",
             ".pytest_cache", ".ruff_cache"}

CONTROL_RE = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")
REPLACEMENT = "�"


def _is_generated_marker(rest: str) -> bool:
    low = rest.lower()
    return any(m in low for m in GENERATED_MARKS)


def _writers(root: Path, tags: set[str]) -> dict[str, list[str]]:
    """Hangi kaynak dosya hangi tag'i aniyor.

    Aranan sey tag adinin kendisidir, `embed_block(..., "TABLO5", ...)` gibi bir
    cagrinin bicimi degil: bir uretecin blogu nasil yazdigi projeye gore
    degisir ve bir cagri kalibini varsaymak, kendi kalibini kullanmayan her
    projede yanlis alarm verirdi.
    """
    found: dict[str, list[str]] = {t: [] for t in tags}
    if not tags:
        return found
    for p in root.rglob("*"):
        if not p.is_file() or p.suffix not in SOURCE_SUFFIXES:
            continue
        if any(part in SKIP_DIRS for part in p.parts):
            continue
        try:
            text = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for tag in tags:
            if tag in text:
                # Koke gore, mutlak degil: mesaj kullanicinin dizin duzenini
                # tasimamali ve iki makinede ayni okunmali.
                try:
                    rel = p.relative_to(root).as_posix()
                except ValueError:
                    rel = p.as_posix()
                found[tag].append(rel)
    return found


def _scan_markers(files_text: dict[str, str]) -> tuple[list[dict], list[dict]]:
    """(bloklar, yapisal sorunlar)"""
    blocks: list[dict] = []
    problems: list[dict] = []
    for fname, text in files_text.items():
        open_at: dict[str, tuple[int, str]] = {}
        for m in MARKER_RE.finditer(text):
            tag, kind = m.group("tag"), m.group("kind")
            start = kind in ("BASLANGIC", "BEGIN")
            if start:
                if tag in open_at:
                    problems.append({
                        "kind": "marker-reopened", "file": fname, "tag": tag,
                        "msg": f"{tag}:{kind} appears twice in {fname} before "
                               f"its closing marker"})
                open_at[tag] = (m.end(), m.group("rest"))
            else:
                if tag not in open_at:
                    problems.append({
                        "kind": "close-without-open", "file": fname, "tag": tag,
                        "msg": f"{tag}:{kind} in {fname} closes a block that "
                               f"was never opened"})
                    continue
                body_start, rest = open_at.pop(tag)
                blocks.append({
                    "file": fname, "tag": tag,
                    "generated": _is_generated_marker(rest),
                    "body_chars": max(0, m.start() - body_start),
                })
        for tag, (_, _rest) in open_at.items():
            problems.append({
                "kind": "unclosed-marker", "file": fname, "tag": tag,
                "msg": f"{tag} is opened in {fname} and never closed"})
    return blocks, problems


def _control_chars(files_text: dict[str, str]) -> list[dict]:
    out = []
    for fname, text in files_text.items():
        # str.splitlines() BOLER on \f, \v, \x1c-\x1e, \x85, U+2028 ve U+2029 —
        # yani tam olarak aradigimiz karakterlerin bir kismini satir sonu sayar
        # ve onlari sayamaz hale getirir (kacan bir \f'in kendisi kaybolur, ondan
        # sonraki satirlarin numarasi da kayar). "\n" ile bolunur.
        for lineno, line in enumerate(text.split("\n"), 1):
            hits = CONTROL_RE.findall(line)
            n_repl = line.count(REPLACEMENT)
            if not hits and not n_repl:
                continue
            entry = {"file": fname, "line": lineno}
            if hits:
                entry["control"] = sorted({"U+%04X" % ord(c) for c in hits})
            if n_repl:
                entry["replacement_chars"] = n_repl
            entry["msg"] = (
                f"{fname}:{lineno} carries "
                + " and ".join(filter(None, [
                    f"{len(hits)} control character(s)" if hits else "",
                    f"{n_repl} U+FFFD replacement character(s)" if n_repl else ""]))
                + " — these come from a tool, not from typing")
            out.append(entry)
    return out


def check(drafts_dir: Path, root: Path) -> dict:
    files = (sorted(p for p in drafts_dir.glob("**/*.md") if p.name != "STATUS.md")
             if drafts_dir.exists() else [])
    files_text = {f.as_posix(): f.read_text(encoding="utf-8", errors="replace")
                  for f in files}

    blocks, marker_problems = _scan_markers(files_text)
    # Her tag aranir, yalnizca "uretilmis" diyenler degil: iki yonlu kontrolun
    # ikinci yarisi tam olarak, betigin yazdigi ama isaretin bunu soylemedigi
    # bloktur.
    all_tags = {b["tag"] for b in blocks}
    writers = _writers(root, all_tags)

    unwritten, undeclared = [], []
    for b in blocks:
        has_writer = bool(writers.get(b["tag"]))
        if b["generated"] and not has_writer:
            unwritten.append({
                "file": b["file"], "tag": b["tag"],
                "body_chars": b["body_chars"],
                "msg": f"{b['tag']} in {b['file']} declares itself generated, "
                       f"but no source file in the project mentions that tag — "
                       f"the block is hand-maintained under a sign that says "
                       f"it is not"})
        elif has_writer and not b["generated"]:
            undeclared.append({
                "file": b["file"], "tag": b["tag"],
                "written_by": writers[b["tag"]],
                "msg": f"{b['tag']} in {b['file']} is written by "
                       f"{', '.join(writers[b['tag']])} but its marker does not "
                       f"say so — a hand edit there is erased on the next run, "
                       f"with nothing having warned against it"})

    controls = _control_chars(files_text)

    return {
        "files_scanned": [f.as_posix() for f in files],
        "blocks_found": len(blocks),
        "generated_blocks": sorted({b["tag"] for b in blocks if b["generated"]}),
        "generated_block_writers": {t: v for t, v in writers.items() if v},
        "unwritten_generated_blocks": unwritten,
        "undeclared_generated_blocks": undeclared,
        "marker_problems": marker_problems,
        "control_characters": controls,
        "warnings": (len(unwritten) + len(undeclared) + len(marker_problems)
                     + len(controls)),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--drafts", default="drafts")
    ap.add_argument("--root", default=".",
                    help="project root scanned for the scripts that write "
                         "generated blocks (default: current directory)")
    ap.add_argument("--strict", action="store_true",
                    help="exit 2 if any warning (opt-in blocking; default is WARN-only)")
    ap.add_argument("--json", dest="json_out", action="store_true")
    args = ap.parse_args()
    require_within_cwd(args.drafts, "--drafts")
    require_within_cwd(args.root, "--root")
    if Path(args.drafts).exists() and not Path(args.drafts).is_dir():
        die(f"--drafts {args.drafts} is not a directory")
    if not Path(args.root).is_dir():
        die(f"--root {args.root} is not a directory")
    result = check(Path(args.drafts), Path(args.root))
    emit(result, True)
    sys.exit(2 if (args.strict and result["warnings"]) else 0)


if __name__ == "__main__":
    try:
        main()
    except OSError as e:
        die(f"failed to read input files — {e}")
    except UnicodeDecodeError as e:
        die(f"a draft file is not valid UTF-8 — {e}")
