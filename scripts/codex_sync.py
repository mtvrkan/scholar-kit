#!/usr/bin/env python3
"""codex_sync.py — generate the Codex half of the kit from the Claude half.

The kit is one body of work read by two harnesses. Its skills, agents, hooks
and constitution are authored once, in Claude Code's formats, under `.claude/`.
Everything OpenAI Codex needs is DERIVED from them by this script and nothing
Codex reads is written by hand, so the two cannot drift apart: `--check` fails
when a generated file is stale, and the test suite runs it.

In the kit repository the Codex half lives in one folder, `codex/`:

  codex/skills/<name>/        <- .claude/skills/<name>/ (verbatim copy), plus
                                 agents/openai.yaml where SKILL.md says
                                 `disable-model-invocation: true`
  codex/agents/<name>.toml    <- .claude/agents/<name>.md
  codex/hooks/hooks.json      <- .claude/settings.json `hooks`
  codex/hooks/codex_adapter.py<- templates/codex/codex_adapter.py
  codex/rules/scholar-kit.rules <- .claude/settings.json `permissions.deny` (Bash)
  codex/AGENTS.md             <- templates/codex/AGENTS.preamble.md + CLAUDE.md

A PROJECT cannot use that folder as it stands: Codex looks for a project's
hooks, agents, rules, instructions and skills at fixed paths. `--project`
writes the same files there instead, from the project's own `.claude/`:

  .agents/skills/  .codex/agents/  .codex/hooks.json  .codex/hooks/
  .codex/rules/    AGENTS.md

What is deliberately NOT derived:
  * a model name. Claude's `model: opus|sonnet|haiku` becomes a reasoning
    effort (high/medium/low); the Codex agent inherits the session's model.
    Writing a model id here would be a claim that goes stale with every
    release.
  * a tool allowlist. Codex custom agents inherit the session's tools; the
    Claude `tools:` line is turned into a stated contract in the agent's
    instructions, and enforced by the agent_write_scope hook via the adapter.
  * `permissions.allow`. A Codex `allow` rule runs the command OUTSIDE the
    sandbox without asking — a wider grant than Claude's allow, so mirroring
    it would loosen the kit. Only the deny list is mirrored (as `forbidden`).
  * Read(...) denies. Codex expresses those as a permission profile in
    config.toml, which would override the user's own sandbox choice;
    docs/CODEX.md gives the snippet instead of imposing it.

Usage:
  python scripts/codex_sync.py                    # kit: write codex/
  python scripts/codex_sync.py --project          # project: write Codex's fixed paths
  python scripts/codex_sync.py --check            # exit 2 if anything is stale
  python scripts/codex_sync.py --python python3   # interpreter for the hook commands
Output is always JSON.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from lib_common import die, emit, parse_frontmatter, write_bytes_atomic

ROOT = Path(__file__).resolve().parent.parent
# Where the adapter sits IN A PROJECT. The hook commands name this path in both
# layouts: the kit's codex/hooks/hooks.json is the file a project receives.
ADAPTER = ".codex/hooks/codex_adapter.py"
GENERATED = "GENERATED by scripts/codex_sync.py"

# Destination of each generated group, per layout. A directory entry ends in
# "/" and is OWNED by this script: anything in it that no source produces is
# removed on sync and reported by --check.
LAYOUTS = {
    "kit": {
        "skills": "codex/skills/",
        "agents": "codex/agents/",
        "hooks": "codex/hooks/hooks.json",
        "adapter": "codex/hooks/codex_adapter.py",
        "rules": "codex/rules/scholar-kit.rules",
        "agents_md": "codex/AGENTS.md",
    },
    "project": {
        "skills": ".agents/skills/",
        "agents": ".codex/agents/",
        "hooks": ".codex/hooks.json",
        "adapter": ADAPTER,
        "rules": ".codex/rules/scholar-kit.rules",
        "agents_md": "AGENTS.md",
    },
}

EFFORT = {"opus": "high", "sonnet": "medium", "haiku": "low"}
_WRITE_TOOLS = {"Write", "Edit", "NotebookEdit"}
_FRONTMATTER_RE = re.compile(r"﻿?---\s*\n.*?\n---\s*\n", re.DOTALL)
# Same two checks patch_hook_interpreter.py applies, for the same reason: the
# token is spliced into a command string a shell later executes on every tool
# call.
_SAFE_TARGET_RE = re.compile(r"^[A-Za-z0-9_./\\:-]+$")
_INTERP_BASENAME_RE = re.compile(r"^(?:python3?(?:\.\d+)*|py)(?:\.exe)?$", re.IGNORECASE)
_HOOK_FILE_RE = re.compile(r"\.claude/hooks/(\w+)\.py")
_EXISTING_INTERP_RE = re.compile(r"then (\S+) \.codex/hooks/")
_SKIP_DIRS = {"__pycache__"}


# ---------- agents ----------

def _toml_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _toml_multiline(text: str) -> str:
    body = text.replace("\\", "\\\\").replace('"""', '""\\"')
    if body.endswith('"'):
        body = body[:-1] + '\\"'
    return '"""\n' + body + '\n"""'


def _tool_contract(tools: list[str]) -> str:
    lines = ["# CODEX TOOL CONTRACT",
             "This role was written for Claude Code, where its frontmatter grants "
             f"exactly these tools: {', '.join(tools)}. Codex gives you the whole "
             "session toolset instead, so the same limits are stated here and "
             "bind you as rules:"]
    writes = bool(set(tools) & _WRITE_TOOLS)
    if not writes:
        lines.append(
            "- READ-ONLY. Never create, modify, move or delete a file — not with "
            "`apply_patch`, not with shell write syntax (`>`, `>>`, `tee`, `cp`, "
            "`mv`, `rm`, `sed -i`, a script that opens a file for writing). "
            "Return your results in your final message; the orchestrator writes.")
    else:
        lines.append(
            "- You may write files with `apply_patch`, but only inside the write "
            "scope your role text declares. The agent_write_scope hook denies "
            "anything outside it.")
    if "Bash" in tools:
        lines.append(
            "- Shell is allowed. `python scripts/<name>.py` calls are the "
            "sanctioned way to change the kit's data files; use them exactly as "
            "your procedure says.")
    else:
        lines.append(
            "- No command execution in the original role. Use the shell only to "
            "READ (`cat`, `sed -n`, `rg`, `ls`); run nothing that changes state "
            "and no script.")
    if not {"WebSearch", "WebFetch"} & set(tools):
        lines.append("- No web access in the original role: do not search or fetch.")
    mcp = [t for t in tools if t.startswith("mcp__")]
    if mcp:
        lines.append(f"- MCP tools of this role: {', '.join(mcp)} (if a server is "
                     "not connected, say so and use the documented fallback).")
    lines.append("- Where the text below names Read/Grep/Glob, use shell read "
                 "commands; Write/Edit means `apply_patch`; WebSearch/WebFetch "
                 "means the web search tool.")
    return "\n".join(lines)


def agent_toml(md_path: Path) -> tuple[str, str]:
    text = md_path.read_text(encoding="utf-8")
    fm = parse_frontmatter(text)
    for field in ("name", "description", "tools", "model"):
        if not fm.get(field):
            die(f"{md_path.name}: frontmatter missing {field}")
    if fm["model"] not in EFFORT:
        die(f"{md_path.name}: model '{fm['model']}' has no reasoning-effort mapping "
            f"(known: {', '.join(EFFORT)})")
    tools = [t.strip() for t in fm["tools"].split(",") if t.strip()]
    body = _FRONTMATTER_RE.sub("", text, count=1).strip()
    instructions = _tool_contract(tools) + "\n\n" + body
    out = (
        f"# {GENERATED} from .claude/agents/{md_path.name} — do not edit.\n"
        f"name = {_toml_string(fm['name'])}\n"
        f"description = {_toml_string(fm['description'])}\n"
        f"model_reasoning_effort = {_toml_string(EFFORT[fm['model']])}\n"
        f"developer_instructions = {_toml_multiline(instructions)}\n")
    return fm["name"], out


# ---------- skills ----------

def skill_files() -> dict[str, bytes]:
    """Every skill, copied byte for byte, plus the Codex sidecar where due.

    Keys are relative to the skills destination. SKILL.md is not rewritten:
    Codex ignores the frontmatter keys it does not know, and one text read by
    both harnesses is the point. The sidecar carries the one thing frontmatter
    cannot say to Codex — that a command runs when named, never implicitly.
    """
    out: dict[str, bytes] = {}
    src_root = ROOT / ".claude" / "skills"
    for skill in sorted(src_root.glob("*/SKILL.md")):
        name = skill.parent.name
        for f in sorted(skill.parent.rglob("*")):
            if not f.is_file() or _SKIP_DIRS & set(f.relative_to(src_root).parts):
                continue
            out[f.relative_to(src_root).as_posix()] = f.read_bytes()
        fm = parse_frontmatter(skill.read_text(encoding="utf-8"))
        if fm.get("disable-model-invocation") == "true":
            sidecar = f"{name}/agents/openai.yaml"
            if sidecar in out:
                die(f".claude/skills/{sidecar} exists — that path is generated for "
                    f"Codex and must not be authored by hand")
            out[sidecar] = (
                f"# {GENERATED} from SKILL.md's `disable-model-invocation: true` — do not edit.\n"
                f"# The skill runs when the user names it (${name}), never implicitly.\n"
                "policy:\n"
                "  allow_implicit_invocation: false\n").encode("utf-8")
    return out


# ---------- hooks ----------

def _codex_matcher(matcher: str) -> str:
    out = []
    for token in matcher.split("|"):
        mapped = "apply_patch" if token in _WRITE_TOOLS else token
        if mapped not in out:
            out.append(mapped)
    return "|".join(out)


def hooks_json(settings: dict, interpreter: str) -> str:
    """The Codex hooks file: same events, same gates, routed through the adapter.

    The command is guarded by a file test because Codex has no
    $CLAUDE_PROJECT_DIR: hooks run in the session's working directory, and a
    bare `python <missing file>` exits 2 — which Codex reads as BLOCK. Started
    from a subdirectory, an unguarded command would deny every tool call.
    """
    win_adapter = ADAPTER.replace("/", "\\")
    events = {}
    for event, groups in (settings.get("hooks") or {}).items():
        new_groups = []
        for group in groups:
            handlers = []
            for h in group.get("hooks", []):
                m = _HOOK_FILE_RE.search(h.get("command", ""))
                if not m:
                    die(f"settings.json {event}: cannot find the hook file in "
                        f"{h.get('command')!r}")
                hook = m.group(1)
                handler = {
                    "type": "command",
                    "command": (f"if [ -f {ADAPTER} ]; then {interpreter} "
                                f"{ADAPTER} {hook}; fi"),
                    "commandWindows": (f"if exist {win_adapter} {interpreter} "
                                       f"{win_adapter} {hook}"),
                }
                if "timeout" in h:
                    handler["timeout"] = h["timeout"]
                handlers.append(handler)
            new_group = {}
            if "matcher" in group:
                new_group["matcher"] = _codex_matcher(group["matcher"])
            new_group["hooks"] = handlers
            new_groups.append(new_group)
        events[event] = new_groups
    doc = {
        "description": (f"{GENERATED} from .claude/settings.json — do not edit. "
                        "Scholar-Kit enforcement gates for Codex; each must be "
                        "trusted once in /hooks before it runs."),
        "hooks": events,
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


# ---------- command rules ----------

def rules_file(settings: dict) -> str:
    lines = [
        f"# {GENERATED} from .claude/settings.json permissions.deny — do not edit.",
        "# Codex command rules (execpolicy). Only the Bash DENY list is mirrored;",
        "# see scripts/codex_sync.py for why `allow` is not.",
        "",
    ]
    for entry in (settings.get("permissions") or {}).get("deny", []):
        m = re.fullmatch(r"Bash\((.+)\)", entry)
        if not m:
            continue
        tokens = m.group(1).split()
        if tokens and tokens[-1] == "*":
            tokens = tokens[:-1]
        if not tokens or any("*" in t for t in tokens):
            die(f"settings.json deny entry {entry!r} is not a plain command prefix")
        example = " ".join(tokens + ["x"])
        lines += [
            "prefix_rule(",
            f"    pattern = {json.dumps(tokens)},",
            '    decision = "forbidden",',
            f"    justification = {json.dumps('Scholar-Kit: mirrors the Claude Code deny rule ' + entry)},",
            f"    match = [{json.dumps(example)}],",
            ")",
            "",
        ]
    return "\n".join(lines)


# ---------- AGENTS.md ----------

def agents_md() -> str:
    preamble = (ROOT / "templates" / "codex" / "AGENTS.preamble.md").read_text(encoding="utf-8")
    constitution = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    if constitution.lstrip().startswith("@"):
        # A CLAUDE.md that only imports another file (`@AGENTS.md`) is not the
        # constitution, and Codex has no import: writing it out would replace
        # the project's real instructions with a dangling reference.
        die("CLAUDE.md is an @import, not the constitution — AGENTS.md cannot be "
            "generated from it")
    return preamble.rstrip("\n") + "\n\n" + constitution


# ---------- driver ----------

def build(interpreter: str, layout: str) -> dict[str, bytes]:
    dest = LAYOUTS[layout]
    settings = json.loads((ROOT / ".claude" / "settings.json").read_text(encoding="utf-8-sig"))
    files: dict[str, bytes] = {}

    def put(rel: str, content) -> None:
        files[rel] = content if isinstance(content, bytes) else content.encode("utf-8")

    for md in sorted((ROOT / ".claude" / "agents").glob("*.md")):
        name, toml = agent_toml(md)
        if name != md.stem:
            die(f"{md.name}: frontmatter name '{name}' differs from the filename")
        put(dest["agents"] + f"{name}.toml", toml)
    for rel, data in skill_files().items():
        put(dest["skills"] + rel, data)
    put(dest["hooks"], hooks_json(settings, interpreter))
    put(dest["adapter"], (ROOT / "templates" / "codex" / "codex_adapter.py").read_bytes())
    put(dest["rules"], rules_file(settings))
    put(dest["agents_md"], agents_md())
    return files


def stale_generated(files: dict[str, bytes], layout: str) -> list[str]:
    """Files in the directories this script owns that no source produces."""
    stale = []
    for key in ("skills", "agents"):
        owned = ROOT / LAYOUTS[layout][key]
        if owned.is_symlink() or not owned.is_dir():
            continue
        for f in owned.rglob("*"):
            rel = f.relative_to(ROOT).as_posix()
            if f.is_file() and rel not in files and not _SKIP_DIRS & set(f.parts):
                stale.append(rel)
    return sorted(stale)


def current_interpreter(layout: str) -> str | None:
    path = ROOT / LAYOUTS[layout]["hooks"]
    if not path.is_file():
        return None
    m = _EXISTING_INTERP_RE.search(path.read_text(encoding="utf-8", errors="replace"))
    return m.group(1) if m else None


def _prune_empty_dirs(layout: str) -> None:
    for key in ("skills", "agents"):
        owned = ROOT / LAYOUTS[layout][key]
        if owned.is_symlink() or not owned.is_dir():
            continue
        for d in sorted((p for p in owned.rglob("*") if p.is_dir()), reverse=True):
            try:
                d.rmdir()
            except OSError:
                pass


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 2 if a generated file is stale")
    ap.add_argument("--project", action="store_true",
                    help="write to the paths Codex reads in a project "
                         "(.codex/, .agents/skills/, AGENTS.md) instead of codex/")
    ap.add_argument("--python", dest="interpreter",
                    help="interpreter the Codex hook commands invoke "
                         "(default: keep the current one, else 'python')")
    ap.add_argument("--json", dest="json_out", action="store_true")
    args = ap.parse_args()

    layout = "project" if args.project else "kit"
    interpreter = args.interpreter or current_interpreter(layout) or "python"
    base = interpreter.replace("\\", "/").rsplit("/", 1)[-1]
    if not _SAFE_TARGET_RE.match(interpreter) or not _INTERP_BASENAME_RE.match(base):
        die(f"--python must be a python/python3/py interpreter token or path, "
            f"got {interpreter!r}")

    files = build(interpreter, layout)
    skills_dir = ROOT / LAYOUTS[layout]["skills"]
    if skills_dir.is_symlink():
        # An earlier layout linked this path to .claude/skills. Writing through
        # the link would put Codex sidecars into the Claude half.
        if args.check:
            emit({"layout": layout, "check": True, "changed": [LAYOUTS[layout]["skills"]],
                  "removed": [], "note": "skills path is a symlink; run without --check"}, True)
            sys.exit(2)
        skills_dir.unlink()

    changed = []
    for rel, content in files.items():
        path = ROOT / rel
        on_disk = path.read_bytes() if path.is_file() else None
        if on_disk != content:
            changed.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                write_bytes_atomic(path, content)
    stale = stale_generated(files, layout)
    if not args.check:
        for rel in stale:
            (ROOT / rel).unlink()
        _prune_empty_dirs(layout)
    emit({"layout": layout, "interpreter": interpreter, "files": len(files),
          "changed": changed, "removed": stale, "check": args.check}, True)
    sys.exit(2 if args.check and (changed or stale) else 0)


if __name__ == "__main__":
    main()
